"""Generate the API and database reference pages from the code and the running database.

    cd backend && DATABASE_URL=postgresql+psycopg://vmo:vmo@localhost:5432/vmo_hotel \
        python ../scripts/gen_reference_docs.py

Writes docs/reference/API.md (every endpoint, from the FastAPI app's OpenAPI description) and
docs/reference/DATABASE.md (every table and view with its columns, keys and indexes, read from
Postgres after `alembic upgrade head`). Both files are overwritten; edit the code or the
migrations, not the generated pages. `make reference-docs` runs this on the host (with the backend
installed) against DATABASE_URL, or the database Docker exposes on port 5432.
"""

from __future__ import annotations

import os
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference"
METHODS = ("get", "post", "put", "patch", "delete")


def _first_line(text: str | None) -> str:
    if not text:
        return ""
    line = text.strip().split("\n\n")[0].replace("\n", " ")
    return re.sub(r"\s+", " ", line).replace("|", "\\|")


def _group(path: str) -> str:
    parts = [p for p in path.split("/") if p]
    if not parts:
        return "/"
    if parts[0] == "api" and len(parts) > 1:
        return "/api/" + parts[1]
    return "/" + parts[0]


def api_doc() -> str:
    os.environ.setdefault("SCHEDULER_ENABLED", "0")
    sys.path.insert(0, str(ROOT / "backend"))
    from app.main import app

    spec = app.openapi()
    groups: dict[str, list[tuple[str, str, str, str]]] = defaultdict(list)
    for path, item in spec["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            body = op.get("requestBody", {}).get("content", {})
            kind = (
                "file upload"
                if "multipart/form-data" in body
                else ("JSON body" if body else "")
            )
            params = [
                p["name"] for p in op.get("parameters", []) if p.get("in") == "query"
            ]
            extra = ", ".join(
                filter(None, [kind, ("query: " + ", ".join(params)) if params else ""])
            )
            text = _first_line(op.get("description")) or op.get("summary", "")
            groups[_group(path)].append((method.upper(), path, text, extra))
    total = sum(len(v) for v in groups.values())
    lines = [
        "# API reference",
        "",
        "Generated by `scripts/gen_reference_docs.py` from the FastAPI application; do not edit by hand.",
        f"{total} endpoints in {len(groups)} groups. The interactive version, with request and response",
        "schemas, is served by the API itself at `/docs` (Swagger UI) and `/openapi.json`.",
        "",
        "Authentication: with `AUTH_MODE=on` every `/api` call needs a session token or an API token",
        "(`Authorization: Bearer ...`), checked by the middleware in `backend/app/main.py`; roles and",
        "property limits apply (see `docs/SECURITY.md`). `/sim/*` endpoints exist only with `SIMULATORS=1`.",
        "",
        "Groups: " + " · ".join(f"[`{g}`](#{_anchor(g)})" for g in sorted(groups)),
        "",
    ]
    for g in sorted(groups):
        lines += [
            f"## `{g}`",
            "",
            "| Method | Path | What it does | Input |",
            "|---|---|---|---|",
        ]
        for m, p, t, e in sorted(
            groups[g], key=lambda r: (r[1], METHODS.index(r[0].lower()))
        ):
            lines.append(f"| {m} | `{p}` | {t} | {e} |")
        lines.append("")
    return "\n".join(lines)


def _anchor(g: str) -> str:
    return re.sub(r"[^a-z0-9 -]", "", g.lower()).replace(" ", "-")


def db_doc() -> str:
    import psycopg

    url = os.environ.get("DATABASE_URL", "postgresql://vmo:vmo@localhost:5432/vmo")
    url = url.replace("postgresql+psycopg://", "postgresql://")
    with psycopg.connect(url) as conn:
        rel = conn.execute(
            "select table_name, table_type from information_schema.tables"
            " where table_schema = 'public' and table_name <> 'alembic_version'"
            " order by table_type, table_name"
        ).fetchall()
        cols = defaultdict(list)
        for t, c, typ, udt, null, default in conn.execute(
            "select table_name, column_name, data_type, udt_name, is_nullable, column_default"
            " from information_schema.columns where table_schema = 'public'"
            " order by table_name, ordinal_position"
        ):
            cols[t].append(
                (c, udt if typ in ("USER-DEFINED", "ARRAY") else typ, null, default)
            )
        pks = defaultdict(set)
        for t, c in conn.execute(
            "select tc.table_name, kcu.column_name from information_schema.table_constraints tc"
            " join information_schema.key_column_usage kcu using (constraint_name, table_schema)"
            " where tc.constraint_type = 'PRIMARY KEY' and tc.table_schema = 'public'"
        ):
            pks[t].add(c)
        fks = defaultdict(dict)
        for t, c, ft, fc, rule in conn.execute(
            "select cl.relname, a.attname, fcl.relname, fa.attname, con.confdeltype"
            " from pg_constraint con"
            " join pg_class cl on cl.oid = con.conrelid"
            " join pg_class fcl on fcl.oid = con.confrelid"
            " join pg_namespace n on n.oid = cl.relnamespace and n.nspname = 'public'"
            " join lateral unnest(con.conkey) with ordinality k(attnum, i) on true"
            " join lateral unnest(con.confkey) with ordinality fk(attnum, i) on fk.i = k.i"
            " join pg_attribute a on a.attrelid = cl.oid and a.attnum = k.attnum"
            " join pg_attribute fa on fa.attrelid = fcl.oid and fa.attnum = fk.attnum"
            " where con.contype = 'f'"
        ):
            on_delete = {"c": " (cascade)", "n": " (set null)"}.get(rule, "")
            fks[t][c] = f"→ `{ft}.{fc}`{on_delete}"
        idx = defaultdict(list)
        for t, name, definition in conn.execute(
            "select tablename, indexname, indexdef from pg_indexes where schemaname = 'public'"
            " and indexname not like '%_pkey' order by tablename, indexname"
        ):
            idx[t].append((name, definition.split(" USING ", 1)[-1]))
        mig = conn.execute("select version_num from alembic_version").fetchone()[0]

    tables = [t for t, k in rel if k == "BASE TABLE"]
    views = [t for t, k in rel if k == "VIEW"]
    lines = [
        "# Database reference",
        "",
        f"Generated by `scripts/gen_reference_docs.py` from Postgres at migration `{mig}`;"
        + " do not edit by hand.",
        f"{len(tables)} tables and {len(views)} views. The schema is owned by the Alembic migrations in",
        "`backend/alembic/versions/`; the reporting views' SQL is in `backend/app/viewsql.py`.",
        "For what the main tables mean and how they connect, read `docs/DATA_MODEL.md` first.",
        "",
        "Tables: " + " · ".join(f"[{t}](#{t})" for t in tables),
        "",
        "Views: " + " · ".join(f"[{t}](#{t})" for t in views),
        "",
    ]
    for t in tables + views:
        kind = "view" if t in views else "table"
        lines += [
            f"## {t}",
            "",
            f"*{kind}*",
            "",
            "| Column | Type | Null | Key / default |",
            "|---|---|---|---|",
        ]
        for c, typ, null, default in cols[t]:
            key = []
            if c in pks[t]:
                key.append("primary key")
            if c in fks[t]:
                key.append(fks[t][c])
            if default and not default.startswith("nextval"):
                key.append(f"default `{default}`")
            lines.append(
                f"| `{c}` | {typ} | {'yes' if null == 'YES' else 'no'} | {'; '.join(key)} |"
            )
        if idx[t]:
            lines += ["", "Indexes: " + "; ".join(f"`{n}` {d}" for n, d in idx[t])]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "API.md").write_text(api_doc() + "\n")
    (OUT / "DATABASE.md").write_text(db_doc() + "\n")
    print(f"Wrote {OUT / 'API.md'} and {OUT / 'DATABASE.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
